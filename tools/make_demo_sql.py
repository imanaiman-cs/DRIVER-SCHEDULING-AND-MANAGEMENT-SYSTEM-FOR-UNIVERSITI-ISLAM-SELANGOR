#!/usr/bin/env python3
"""
Writes the DEMO DATA section of database.sql from a database filled by tools/seed_demo.php.

    python3 tools/make_demo_sql.py      (replaces everything after the "-- DEMO DATA" marker in database.sql)

Dates are written relative to the day of the import, so the demo always shows upcoming trips, pending approvals and
past reports:  TIMESTAMP(DATE_ADD(CURDATE(), INTERVAL n DAY), 'hh:mm:ss').  Welfare duty keeps its weekdays: its dates
are relative to the Monday of the week of the import.
"""
import datetime as dt, os, re, subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DB = 'uis_driver_db'
TABLES = ['requests', 'request_vehicles', 'request_documents', 'welfare_weeks', 'tasks', 'task_reports', 'schedule_changes',
          'driver_replacements', 'request_history', 'notifications']
MARK = '-- ============================================================\n-- DEMO DATA'

today = dt.datetime.now(dt.timezone(dt.timedelta(hours=8))).date()   # Malaysia time, like the SET time_zone of database.sql
monday = today - dt.timedelta(days=today.weekday())


def q(sql):
    return subprocess.run(['mysql', '-uroot', '-N', '-B', DB, '-e', sql], capture_output=True, text=True, check=True).stdout


def rel(lit, weekly=False):
    s = lit.strip("'")
    if re.fullmatch(r'\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2}', s):
        d = dt.date.fromisoformat(s[:10])
        base, n = ("DATE_SUB(CURDATE(), INTERVAL WEEKDAY(CURDATE()) DAY)", (d - monday).days) if weekly else ('CURDATE()', (d - today).days)
        return f"TIMESTAMP(DATE_ADD({base}, INTERVAL {n} DAY), '{s[11:]}')"
    if re.fullmatch(r'\d{4}-\d{2}-\d{2}', s):
        d = dt.date.fromisoformat(s)
        base, n = ("DATE_SUB(CURDATE(), INTERVAL WEEKDAY(CURDATE()) DAY)", (d - monday).days) if weekly else ('CURDATE()', (d - today).days)
        return f"DATE_ADD({base}, INTERVAL {n} DAY)"
    return lit


def main():
    dump = subprocess.run(['mysqldump', '-uroot', '--no-create-info', '--complete-insert', '--skip-extended-insert', '--skip-triggers',
                           '--compact', DB] + TABLES, capture_output=True, text=True, check=True).stdout
    welfare_tasks = set(q("SELECT task_id FROM tasks WHERE task_source = 'welfare'").split())
    lines = []
    for line in dump.splitlines():
        if not line.startswith('INSERT INTO'):
            continue
        table = re.match(r'INSERT INTO `(\w+)`', line).group(1)
        weekly = table == 'welfare_weeks'
        if table == 'tasks':
            tid = re.search(r'VALUES \((\d+),', line).group(1)
            weekly = tid in welfare_tasks
        if table == 'request_documents':
            line = re.sub(r"'uploads/documents/[0-9a-f]+\.pdf'", "'uploads/documents/demo_supporting_letter.pdf'", line)
        line = re.sub(r"'\d{4}-\d{2}-\d{2}(?: \d{2}:\d{2}:\d{2})?'", lambda m: rel(m.group(0), weekly), line)
        lines.append(line)
    # the vehicles' mileage, fuel level and status after the demo reports
    for vid, mil, fuel, st in [r.split('\t') for r in q('SELECT vehicle_id, current_mileage, fuel_level, status FROM vehicles').strip().splitlines()]:
        lines.append(f"UPDATE vehicles SET current_mileage = {mil}, fuel_level = '{fuel}', status = '{st}' WHERE vehicle_id = {vid};")
    section = (MARK + ' (generated by tools/seed_demo.php + tools/make_demo_sql.py; dates relative to the day of the import)\n'
               '-- ============================================================\n'
               'SET FOREIGN_KEY_CHECKS = 0;\nDROP TRIGGER IF EXISTS trg_history_no_update;\n' + '\n'.join(lines) +
               "\nCREATE TRIGGER trg_history_no_update BEFORE UPDATE ON request_history FOR EACH ROW SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'request_history is insert-only';\n"
               'SET FOREIGN_KEY_CHECKS = 1;\n')
    path = os.path.join(ROOT, 'database.sql')
    sql = open(path).read()
    if MARK in sql:
        sql = sql[:sql.index(MARK)]
    open(path, 'w').write(sql.rstrip('\n') + '\n\n' + section)
    print(f'{len(lines)} demo statements written to database.sql')


if __name__ == '__main__':
    main()
